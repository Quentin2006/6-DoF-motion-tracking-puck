#!/usr/bin/env python3
"""Emit the cross-half wire constants from tools/wire_spec.json.

One spec, two generated files:
  device/wire.h      C++ constexprs  (host-compilable: no Arduino, no Rust)
  engine/src/wire.rs Rust consts

Neither file is hand-edited: change tools/wire_spec.json and run
`make gen-wire`. `make wire-check` re-runs this with --check and fails if
either generated file on disk has drifted.

Output is deterministic (spec key order, no timestamps) so the --check diff is
meaningful. Python 3 stdlib only.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "tools" / "wire_spec.json"
TARGETS = {
    "cpp": ROOT / "device" / "wire.h",
    "rust": ROOT / "engine" / "src" / "wire.rs",
}
HEADER = "GENERATED by tools/gen_wire.py from tools/wire_spec.json - DO NOT EDIT"

# The C++ side keeps the exact type each constant had before generation, so no
# call site changes signedness or width. The Rust side uses the same intent:
# u8/u16 mirror the wire, usize mirrors a byte count or size_t.
CPP_TYPE = {
    "int": "int",
    "u8": "uint8_t",
    "u16": "uint16_t",
    "usize": "size_t",
}
RUST_TYPE = {
    "int": "u32",
    "u8": "u8",
    "u16": "u16",
    "usize": "usize",
}
HEX_WIDTH = {"u8": 2, "u16": 4}


def load_spec() -> list[tuple[str, int, str, str]]:
    entries = json.loads(SPEC.read_text())
    out = []
    for name, spec in entries.items():
        kind = spec.get("type", "int")
        if kind not in CPP_TYPE:
            raise SystemExit(f"{name}: unknown type {kind!r}")
        out.append((name, spec["value"], kind, spec["doc"]))
    return out


def literal(value: int, kind: str) -> str:
    if kind in HEX_WIDTH:
        return f"0x{value:0{HEX_WIDTH[kind]}X}"
    return str(value)


def render_cpp(entries) -> str:
    lines = [
        f"// {HEADER}",
        "//",
        "// The single source is tools/wire_spec.json. Host-compilable on purpose:",
        "// no Arduino, no Rust, so tests/*.cpp can include it directly.",
        "// A classic guard, not #pragma once: arduino-cli stages the sketch into",
        "// build/sketch/, so video.h's \"../../wire.h\" and config.h's \"wire.h\"",
        "// resolve to two copies of this file. A macro guard dedupes across both;",
        "// #pragma once does not.",
        "#ifndef PUCK_WIRE_H",
        "#define PUCK_WIRE_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
    ]
    for name, value, kind, doc in entries:
        lines.append(f"constexpr {CPP_TYPE[kind]} {name} = {literal(value, kind)}; // {doc}")
    lines += ["", "#endif  // PUCK_WIRE_H"]
    return "\n".join(lines) + "\n"


def render_rust(entries) -> str:
    lines = [
        f"// {HEADER}",
        "//",
        "// The single source is tools/wire_spec.json. Change that, then",
        "// `make gen-wire`; `make wire-check` fails on drift.",
    ]
    for name, value, kind, doc in entries:
        lines.append(f"pub const {name}: {RUST_TYPE[kind]} = {literal(value, kind)}; // {doc}")
    return "\n".join(lines) + "\n"


def main() -> int:
    entries = load_spec()
    rendered = {"cpp": render_cpp(entries), "rust": render_rust(entries)}
    check = "--check" in sys.argv[1:]
    drift = []
    for key, path in TARGETS.items():
        want = rendered[key]
        if check:
            have = path.read_text() if path.exists() else ""
            if have != want:
                drift.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want)
            print(f"wrote {path.relative_to(ROOT)}")
    if drift:
        for path in drift:
            print(f"wire-check: {path} differs from tools/wire_spec.json; run `make gen-wire`")
        return 1
    if check:
        print("wire-check OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
